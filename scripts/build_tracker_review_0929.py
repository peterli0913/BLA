def style_sheet(ws, head, widths, center_cols):
    thin = Side(style="thin", color="BFBFBF")
    border = Border(left=thin, right=thin, top=thin, bottom=thin)
    wrap = Alignment(wrap_text=True, vertical="top")
    center = Alignment(wrap_text=True, vertical="center", horizontal="center")
    for c in ws[1]:
        c.font = Font(name="微软雅黑", bold=True, color="FFFFFF", size=11)
        c.fill = PatternFill("solid", fgColor="2F5597")
        c.alignment = center
        c.border = border
    for r in ws.iter_rows(min_row=2, max_row=ws.max_row):
        for c in r:
            c.font = Font(name="微软雅黑", size=10)
            c.alignment = center if c.column in center_cols else wrap
            c.border = border
    ws.row_dimensions[1].height = 24
    for i, w in enumerate(widths, 1):
        ws.column_dimensions[chr(64 + i)].width = w
    # openpyxl cannot autofit, so estimate wrapped line count (CJK chars take two width units).
    for r in range(2, ws.max_row + 1):
        lines = 1
        for c in range(1, len(head) + 1):
            text = str(ws.cell(r, c).value or "")
            usable = max(widths[c - 1] - 2, 1)
            n = sum(max(1, math.ceil(sum(2 if ord(ch) > 0x2E80 else 1 for ch in part) / usable))
                    for part in text.split("\n"))
            lines = max(lines, n)
        ws.row_dimensions[r].height = 14 * lines + 6
    ws.freeze_panes = "A2"
    ws.auto_filter.ref = f"A1:{chr(64 + len(head))}{ws.max_row}"
    ws.page_setup.orientation = "landscape"
    ws.page_setup.fitToWidth = 1
    ws.page_setup.fitToHeight = 0
    ws.sheet_properties.pageSetUpPr.fitToPage = True
    ws.print_title_rows = "1:1"


