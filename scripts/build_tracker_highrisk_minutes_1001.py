def add_topic(doc, t):
    add_h2(doc, t["title"])
    rows = [["礼来关注 / 要求", "\n".join(f"• {s}" for s in t["lilly"])],
            ["我方会上回应", "\n".join(f"• {s}" for s in t["ours"])]]
    if t.get("internal"):
        rows.append(["我方内部讨论", t["internal"]])
    rows += [["会上共识", t["consensus"]], ["我方薄弱点（内部）", t["gap"]]]
    add_table(doc, ["项目", "内容"], rows, [3.0, 14.6], size=9.5, first_col_bold=True)


