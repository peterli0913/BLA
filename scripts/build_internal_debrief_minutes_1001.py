def add_topic(doc, t):
    add_h2(doc, t["title"])
    rows = [["讨论要点", "\n".join(f"• {s}" for s in t["points"])],
            ["内部共识与做法", "\n".join(f"• {s}" for s in t["agreed"])]]
    if t["open"] != "—":
        rows.append(["分歧 / 未决", t["open"]])
    add_table(doc, ["项目", "内容"], rows, [3.0, 14.6], size=9.5, first_col_bold=True)


